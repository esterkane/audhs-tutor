import axe from 'axe-core'
import { test, expect } from '@playwright/test'
for (const width of [390, 1280]) {
  test(`visual learning transfer and controls ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/playground/visual-learning')
    await expect(page.getByRole('heading', { name: 'Keep test data out of training' })).toBeVisible()
    const slider = page.getByRole('slider')
    await page.getByRole('combobox').focus()
    await page.keyboard.press('Tab')
    await expect(slider).toBeFocused()
    await page.keyboard.press('ArrowRight')
    await expect(slider).toHaveValue('11')
    await expect(page.getByRole('status').filter({ hasText: 'Fitted mean' })).toContainText('Fitted mean: 3.')
    await page.getByRole('combobox').selectOption('all')
    await expect(page.getByRole('status').filter({ hasText: 'Fitted mean' })).toContainText('Fitted mean: 7.5.')
    await page.getByRole('radio', { name: 'Find one median using all patients.' }).check()
    await page.getByRole('button', { name: 'Check my reasoning' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Using all patients' })).toBeVisible()
    await page.getByRole('radio', { name: 'Learn the training median and use it for both sets.' }).focus()
    await page.keyboard.press('Space')
    await page.getByRole('button', { name: 'Check my reasoning' }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('status').filter({ hasText: 'Correct for this scenario' })).toBeVisible()
    await page.getByRole('button', { name: 'Reset experiment' }).click()
    await expect(slider).toHaveValue('10')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.addScriptTag({ content: axe.source })
    const violations = await page.evaluate(async () => (await (window as unknown as { axe: typeof axe }).axe.run('main')).violations)
    expect(violations).toEqual([])
    await page.screenshot({ path: info.outputPath('visual-learning.png'), fullPage: true })
    await page.getByRole('link', { name: '← Return to coding playground' }).click()
    await expect(page).toHaveURL(/\/playground$/)
  })
}

import { expect, test } from '@playwright/test'
import { API, currentSession, endOpenSession, expectOk } from './helpers'

for (const theme of ['light', 'dark'])
for (const width of [320, 390, 1280]) test(`lesson leads before optional tools ${width} ${theme}`, async ({ page, request }, info) => {
  await endOpenSession(request)
  try {
    await expectOk(await request.put(`${API}/api/preferences`, { data: { key: 'ui.theme', value: theme } }))
    for (const key of ['goal.area', 'goal.course'])
      await request.put(`${API}/api/preferences`, { data: { key, value: '' } })
    const response = await request.post(`${API}/api/sessions`, { data: { mode: 'steady', energy: 3 } })
    await expectOk(response)
    const session = await response.json()
    const index = session.plan.findIndex((block: { type: string }) => block.type === 'new_material')
    await expectOk(await request.post(`${API}/api/plan/blocks/start`, { data: { session_id: session.id, index } }))
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.getByRole('button', { name: 'Continue', exact: true }).click()
    const explanation = page.getByRole('heading', { name: 'Your explanation' })
    await expect(explanation).toBeVisible()
    await expect.poll(() => page.evaluate(() => getComputedStyle(document.body).backgroundColor)).toBe(theme === 'dark' ? 'rgb(29, 30, 36)' : 'rgb(247, 248, 252)')
    for (const label of ['Session plan and energy settings', 'More ways to learn']) {
      const disclosure = page.locator('summary').filter({ hasText: label })
      const box = await disclosure.boundingBox()
      expect(box!.height, `${label} touch target`).toBeGreaterThanOrEqual(44)
    }
    await page.screenshot({ path: info.outputPath('lesson.png'), fullPage: true })
    const start = page.getByRole('button', { name: 'Start explanation', exact: true })
    const tools = page.locator('summary').filter({ hasText: /^Work alongside$/ })
    let startBox = await start.boundingBox()
    const planSettings = page.locator('summary').filter({ hasText: /^Session plan and energy settings$/ })
    expect((await planSettings.boundingBox())!.y).toBeGreaterThan(startBox!.y)
    await planSettings.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Energy 3', exact: true })).toBeVisible()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Energy 3', exact: true })).not.toBeVisible()

    expect(startBox!.height).toBeGreaterThanOrEqual(44)
    const standardVisual = await start.evaluate(el => {
      const style = getComputedStyle(el, '::before')
      return el.getBoundingClientRect().height - parseFloat(style.top) - parseFloat(style.bottom)
    })
    expect(standardVisual).toBeGreaterThanOrEqual(40)
    const planToggle = page.locator('summary').filter({ hasText: 'Session plan and energy settings' })
    await planToggle.click()
    const energyOne = page.getByRole('button', { name: 'Energy 1', exact: true })
    const energyTwo = page.getByRole('button', { name: 'Energy 2', exact: true })
    await energyOne.scrollIntoViewIfNeeded()
    const firstEnergy = await energyOne.boundingBox()
    const secondEnergy = await energyTwo.boundingBox()
    expect(firstEnergy!.width).toBeGreaterThanOrEqual(44)
    expect(firstEnergy!.height).toBeGreaterThanOrEqual(44)
    expect(firstEnergy!.x + firstEnergy!.width).toBeLessThanOrEqual(secondEnergy!.x)
    expect(await energyOne.evaluate(el => {
      const r = el.getBoundingClientRect()
      return document.elementFromPoint(r.x + r.width / 2, r.y + 1) === el
    })).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await planToggle.click()

    startBox = await start.boundingBox()
    const toolsBox = await tools.boundingBox()
    console.log(JSON.stringify({ width, startTop: startBox?.y, toolsTop: toolsBox?.y }))
    expect(startBox!.y).toBeLessThan(toolsBox!.y)
    if (width < 1280) await page.getByRole('button', { name: 'Learning context', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Learning goal', exact: true })).toBeVisible()
    if (width < 1280) {
      await page.screenshot({ path: info.outputPath('context-flyout.png') })
      await page.keyboard.press('Escape')
      await expect(page.getByRole('button', { name: 'Learning context', exact: true })).toBeFocused()
    }
    if (width === 320 && theme === 'light') {
      const draft = page.getByLabel('Ask about this lesson (optional)')
      await draft.fill('Keep my question through resize')
      await page.getByRole('button', { name: 'Learning context', exact: true }).click()
      await page.setViewportSize({ width: 1280, height: 900 })
      await expect(page.getByRole('heading', { name: 'Learning context', exact: true })).toBeFocused()
      await expect(draft).toHaveValue('Keep my question through resize')
      await page.setViewportSize({ width: 390, height: 900 })
      await expect(page.getByRole('button', { name: 'Learning context', exact: true })).toBeFocused()
      await page.getByRole('button', { name: 'Focus on lesson', exact: true }).click()
      await page.getByRole('button', { name: 'Learning context', exact: true }).click()
      await page.setViewportSize({ width: 1280, height: 900 })
      await expect(page.getByRole('button', { name: 'Learning context', exact: true })).toBeFocused()
      await expect(draft).toHaveValue('Keep my question through resize')
      await page.getByRole('button', { name: 'Leave focus · Esc', exact: true }).click()
      await page.setViewportSize({ width, height: 900 })
      await draft.fill('')
      startBox = await start.boundingBox()
    }
    const audioBox = await page.getByRole('button', { name: 'Listen to learning goal', exact: true }).boundingBox()
    expect(startBox!.y).toBeLessThan(audioBox!.y)
    const audio = page.locator('main summary').filter({ hasText: /^Audio controls/ }).first()
    expect((await audio.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await audio.focus()
    await page.keyboard.press('Enter')
    await expect(audio.locator('..').getByRole('slider', { name: 'Audio volume' })).toBeVisible()
    await page.keyboard.press('Enter')
    await expect(audio.locator('..').getByRole('slider', { name: 'Audio volume' })).not.toBeVisible()
    await start.focus()
    await page.keyboard.press('Tab')
    await expect(page.locator('summary').filter({ hasText: /^More ways to learn$/ })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Hint', exact: true })).toBeVisible()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Hint', exact: true })).not.toBeVisible()
    await page.getByLabel('Ask about this lesson (optional)').focus()
    await page.keyboard.press('Tab')
    await expect(start).toBeFocused()
    const controls = page.getByRole('region', { name: 'Session controls' })
    await expect(controls.getByRole('button', { name: 'End session', exact: true })).not.toBeVisible()
    await expect(controls.getByRole('button', { name: 'Change topic' })).not.toBeVisible()
    const checkpoint = await currentSession(request)
    const labels = controls.locator('summary').filter({ hasText: /^Session options$/ })
    await labels.focus()
    await page.keyboard.press('Enter')
    await expect(controls.getByRole('button', { name: 'End session', exact: true })).toBeVisible()
    await expect(controls.getByRole('button', { name: 'Change topic' })).toBeVisible()
    await controls.getByRole('button', { name: 'This is clear' }).click()
    await expect(controls.getByRole('status')).toContainText('Saved as clear for you.')
    await labels.focus()
    await page.keyboard.press('Enter')
    await expect(controls.getByRole('status')).toBeVisible()
    await expect(controls.getByRole('button', { name: 'Undo label' })).not.toBeVisible()
    await labels.focus()
    await page.keyboard.press('Enter')
    await controls.getByRole('button', { name: 'Undo label' }).click()
    await expect(controls.getByRole('status')).toHaveCount(0)
    await labels.focus()
    await page.keyboard.press('Enter')
    expect(await currentSession(request)).toEqual(checkpoint)
    await tools.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByText('Keep this lesson open with a quiet work panel.', { exact: false })).toBeVisible()
    await tools.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('link', { name: 'Open lesson experiment' })).not.toBeVisible()
    const code = page.locator('summary').filter({ hasText: /^Try a coding experiment$/ })
    await code.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('link', { name: 'Open lesson experiment' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Pause and return Home' }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeVisible()
  } finally {
    await endOpenSession(request)
    await request.put(`${API}/api/preferences`, { data: { key: 'ui.theme', value: 'light' } })
  }
})

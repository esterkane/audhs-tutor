test('Lost review remains recoverable after document is archived', async ({ page }) => {
  const calls = await fixture(page)
  await page.goto('/ask?answer=visual-answer')
  await page.getByText('Visual explanation (optional)', { exact: true }).click()
  await page.getByRole('button', { name: 'Generate local diagram', exact: true }).click()
  calls.complete()
  await page.getByRole('button', { name: 'Refresh visual status' }).click()
  await page.getByText('Review this diagram · version 1', { exact: true }).click()
  await page.getByRole('textbox', { name: 'What works or needs correction? (optional)' }).fill('Keep this exact note.')
  calls.loseReview()
  await page.getByRole('button', { name: 'Needs correction', exact: true }).click()
  await expect(page.getByRole('button', { name: /Retry previous/ })).toBeVisible()
  await page.route('**/api/authored-visuals?*', route => route.fulfill({ json: new URL(route.request().url()).searchParams.get('archived') === 'true' ? [{ id: 'doc', title: 'Archived diagram', revision: 3, archived: true }] : [] }))
  await page.reload()
  await page.getByText('Visual explanation (optional)', { exact: true }).click()
  await page.getByRole('checkbox', { name: 'Show archived diagrams' }).check()
  await page.getByText('Review history · version 1', { exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'What works or needs correction? (optional)' })).toHaveValue('Keep this exact note.')
  await page.getByRole('button', { name: /Retry previous/ }).click()
  await expect(page.getByText('Review saved for version 1. Your note is kept below.')).toBeVisible()
  expect(calls.reviews).toHaveLength(1)
  expect(calls.reviewKeys[0]).toBe(calls.reviewKeys[1])
  await expect(page.getByRole('button', { name: 'Needs correction', exact: true })).toHaveCount(0)
})

import { expect, test } from '@playwright/test'
import { API, endOpenSession, expectOk, freshDeterministicSkill } from './helpers'

for (const width of [390, 1280]) test(`revise the saved answer with reload and cancel ${width}`, async ({ page, request }, info) => {
  await endOpenSession(request)
  try {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ colorScheme: width === 1280 ? 'dark' : 'light' })
    await request.put(`${API}/api/preferences`, { data: { key: 'goal.area', value: '' } })
    await request.put(`${API}/api/preferences`, { data: { key: 'goal.course', value: '' } })
    const response = await request.post(`${API}/api/sessions`, { data: { mode: 'steady', energy: 3 } })
    await expectOk(response)
    const session = await response.json()
    const index = session.plan.findIndex((b: { type: string }) => b.type === 'new_material')
    await expectOk(await request.post(`${API}/api/plan/blocks/start`, { data: { session_id: session.id, index } }))
    await expectOk(await request.post(`${API}/api/sessions/${session.id}/checkpoint`, { data: { phase: 'assess', skill_id: freshDeterministicSkill() } }))
    const submissions: Record<string, unknown>[] = []
    await page.route('**/api/assess/attempt', async route => {
      submissions.push(route.request().postDataJSON())
      await route.continue()
    })
    await page.goto('/')
    await page.getByRole('button', { name: /^Continue$/ }).click()
    const choices = page.getByRole('group', { name: 'Your answer', exact: true })
    const field = page.getByRole('textbox', { name: 'Your answer', exact: true })
    await expect(page.getByRole('button', { name: 'Check my answer', exact: true })).toBeVisible()
    const mcq = await choices.count() > 0
    if (mcq) await choices.getByRole('button').first().click()
    else await field.fill('0')
    await page.getByRole('button', { name: 'Check my answer', exact: true }).click()
    const again = page.getByRole('button', { name: 'Try again', exact: true })
    await expect(again).toBeVisible()
    await again.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Try this question again' })).toBeVisible()
    const input = mcq ? choices.getByRole('button').first() : field
    await expect(input).toBeFocused()
    if (mcq) await choices.getByRole('button').nth(1).click()
    else await field.fill('5')
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Try this question again' })).toBeVisible()
    await expect(input).toBeFocused()
    if (mcq) await expect(choices.getByRole('button').nth(1)).toHaveAttribute('aria-pressed', 'true')
    else await expect(field).toHaveValue('5')
    expect(submissions).toHaveLength(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ path: info.outputPath('revision.png') })
    await page.getByRole('button', { name: 'Cancel revision', exact: true }).click()
    await expect(again).toBeFocused()
    expect(submissions).toHaveLength(1)
    await again.click()
    await expect(input).toBeFocused()
    if (mcq) await choices.getByRole('button').nth(1).click()
    else await field.fill('5')
    await page.getByRole('button', { name: 'Check my answer', exact: true }).click()
    await expect(page.getByText(/Repeated practice on a previously checked question/)).toBeVisible()
    expect(submissions).toHaveLength(2)
    expect(submissions[1].revision_of_attempt_id).toBeTruthy()
    await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeEnabled()
  } finally { await endOpenSession(request) }
})

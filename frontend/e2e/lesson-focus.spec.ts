import { expect, test } from '@playwright/test'
import { API, currentSession, endOpenSession, expectOk } from './helpers'

for (const width of [320, 1280]) test(`focus retains work, exits and global recovery ${width}`, async ({ page, request }, info) => {
  await endOpenSession(request)
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  try {
    await request.put(`${API}/api/preferences`, { data: { key: 'ui.theme', value: width === 320 ? 'dark' : 'light' } })
    for (const key of ['goal.area', 'goal.course']) await request.put(`${API}/api/preferences`, { data: { key, value: '' } })
    const response = await request.post(`${API}/api/sessions`, { data: { mode: 'steady', energy: 3 } })
    await expectOk(response)
    const session = await response.json()
    const index = session.plan.findIndex((block: { type: string }) => block.type === 'new_material')
    await expectOk(await request.post(`${API}/api/plan/blocks/start`, { data: { session_id: session.id, index } }))
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await page.getByRole('button', { name: 'Continue', exact: true }).click()
    const draft = page.getByLabel('Ask about this lesson (optional)')
    await draft.fill('Keep this question through focus changes.')
    const alongside = page.locator('summary').filter({ hasText: /^Work alongside$/ })
    await alongside.click()
    await expect(page.getByRole('heading', { name: 'Working alongside' })).toBeVisible()
    const checkpoint = await currentSession(request)
    const enter = page.getByRole('button', { name: 'Focus on lesson', exact: true })
    await enter.focus()
    await page.keyboard.press('Enter')
    const leave = page.getByRole('button', { name: 'Leave focus · Esc', exact: true })
    await expect(leave).toBeFocused()
    await expect(alongside).not.toBeVisible()
    await expect(page.locator('summary').filter({ hasText: /^Try a coding experiment$/ })).not.toBeVisible()
    await expect(page.locator('summary').filter({ hasText: /^Session plan and energy settings$/ })).not.toBeVisible()
    await expect(page.locator('header')).not.toBeVisible()
    expect((await page.locator('main').boundingBox())!.width).toBeLessThanOrEqual(896)
    await expect(page.getByRole('navigation', { name: 'Main navigation' })).not.toBeVisible()
    await expect(draft).toHaveValue('Keep this question through focus changes.')
    await page.keyboard.press('Control+k')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: 'Save for later', exact: true }).click()
    const thought = page.getByRole('textbox', { name: 'Thought to save' })
    await thought.fill('Retain my focused thought')
    await page.keyboard.press('Escape')
    await expect(leave).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save for later', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(enter).toBeFocused()
    await expect(alongside).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Working alongside' })).toBeVisible()
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: 'Save for later', exact: true }).click()
    await expect(thought).toHaveValue('Retain my focused thought')
    await page.getByRole('button', { name: 'Save thought', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Thought saved.' })).toBeVisible()
    await page.route('**/api/voice/speak', async route => {
      await held
      await route.fulfill({ json: { pcm16_b64: Buffer.alloc(48000).toString('base64'), sample_rate: 24000 } })
    })
    await page.getByRole('button', { name: 'Listen to learning goal', exact: true }).click()
    const stop = page.getByRole('region', { name: 'Session controls' }).getByRole('button', { name: 'Stop audio', exact: true })
    await expect(stop).toBeVisible()
    await stop.focus()
    await page.keyboard.press('Enter')
    await expect(leave).toBeFocused()
    await page.screenshot({ path: info.outputPath('focus.png'), fullPage: true })
    await page.keyboard.press('Escape')
    await expect(enter).toBeVisible()
    await expect(page.locator('header')).toBeVisible()
    await expect(draft).toHaveValue('Keep this question through focus changes.')
    expect(await currentSession(request)).toEqual(checkpoint)
    await enter.click()
    await draft.focus()
    await page.keyboard.press('Escape')
    await expect(draft).toBeFocused()
    await enter.click()
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('focus-large-text.png'), fullPage: true })
    await page.evaluate(() => { document.documentElement.style.fontSize = '' })
    await page.getByRole('button', { name: 'Pause and return Home' }).click()
    await expect(page.locator('header')).toBeVisible()
    await page.goBack()
    await expect(enter).toBeVisible()
    await enter.click()
    await page.reload()
    await expect(enter).toBeVisible()
    await expect(draft).toHaveValue('Keep this question through focus changes.')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally {
    release()
    await endOpenSession(request)
    await request.put(`${API}/api/preferences`, { data: { key: 'ui.theme', value: 'light' } })
  }
})

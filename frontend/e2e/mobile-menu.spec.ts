import {expect,test} from '@playwright/test'
import axe from 'axe-core'
test('mobile library navigation preserves orientation through resizing and return',async({page},info)=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/library')
 const nav=page.getByRole('navigation',{name:'Main navigation',exact:true})
 await expect(nav.getByRole('link')).toHaveCount(6)
 const source=page.getByRole('searchbox',{name:'Search phrase'})
 await source.focus()
 await page.setViewportSize({width:1280,height:900})
 await expect(source).toBeFocused()
 await expect(source).toBeVisible()
 await expect(nav.getByRole('link',{name:'Library',exact:true})).toHaveAttribute('aria-current','page')
 await expect(page).toHaveTitle('Library · AuDHS Tutor')
 await page.setViewportSize({width:390,height:844})
 await page.addScriptTag({content:axe.source})
 expect(await page.evaluate(async()=>(await (window as unknown as {axe:typeof axe}).axe.run('main')).violations)).toEqual([])
 await page.screenshot({path:info.outputPath('library-mobile-final.png'),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})

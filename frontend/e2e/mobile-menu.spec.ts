import { expect, test } from '@playwright/test'

test('mobile tools sheet preserves focus through resize and navigation', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/local-learning/program.json', route => route.fulfill({ json: { title: 'Fixture', courses: [] } }))
  await page.goto('/curriculum')
  const tools = page.getByRole('button', { name: 'Tools', exact: true })
  const nav = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  await expect(nav).toBeVisible()
  await tools.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Tools and pages' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('link', { name: 'Project study', exact: true }).focus()
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect(dialog.getByRole('link', { name: 'Project study', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(tools).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(tools).toBeFocused()
  await tools.click()
  await dialog.getByRole('link', { name: 'Project study', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page).toHaveURL(/\/programs$/)
  await page.goBack()
  await expect(page).toHaveTitle('Lesson drafts · AuDHS Tutor')
  await expect(dialog).toBeHidden()
  await expect(nav).toBeVisible()
  await page.screenshot({ path: info.outputPath('mobile-tools-closed.png'), fullPage: true })
})

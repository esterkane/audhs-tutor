import { expect, test } from '@playwright/test'
import axe from 'axe-core'

for (const width of [390, 1280]) test(`optional quiet designs respect reduced motion at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/together')
  const select = page.getByLabel('Break design', { exact: true })
  await expect(select).toHaveValue('off')
  await expect(page.locator('[data-break-design]')).toHaveCount(0)
  await select.selectOption('frost')
  const graphic = page.locator('[data-break-design="frost"]')
  await expect(graphic).toBeVisible()
  const before = await graphic.innerHTML()
  await page.getByRole('button', { name: 'Change pattern' }).focus()
  await page.keyboard.press('Enter')
  expect(await graphic.innerHTML()).not.toBe(before)
  await select.selectOption('liquid')
  await expect(page.locator('[data-break-design="liquid"]')).toBeVisible()
  await page.reload()
  await expect(select).toHaveValue('liquid')
  await expect(page.locator('[data-break-design="liquid"]')).toBeVisible()
  await page.addScriptTag({ content: axe.source })
  expect(await page.evaluate(async () => (await (window as unknown as { axe: typeof axe }).axe.run('main')).violations)).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('quiet-liquid.png'), fullPage: true })
  await select.selectOption('off')
  await expect(page.locator('[data-break-design]')).toHaveCount(0)
})
